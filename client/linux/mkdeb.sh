#!/usr/bin/env bash
#
# Luminum Client (Linux) .deb packager
# by Christopher R. Curzio (ccurzio@luminum.net)
#
# Builds a self-contained Debian binary package (luminum-client) that installs
# the Luminum client to /opt/Luminum/LuminumClient and sets up its systemd
# service. The package carries the prebuilt client binary (and any prebuilt
# Lumy module binaries it finds); it does NOT carry an infra-specific
# config.ini, so the client is left unconfigured until the operator imports a
# provisioning file (LuminumClient --import) or runs the wizard
# (LuminumClient -s). If the operator places a config.ini at the install root
# before or after install, postinst imports it so the client is pre-configured.
#
# Installed layout:
#   /opt/Luminum/LuminumClient/LuminumClient        client binary
#   /opt/Luminum/LuminumClient/bin/start-client     start/stop scripts
#   /opt/Luminum/LuminumClient/bin/stop-client
#   /opt/Luminum/LuminumClient/config/              client.conf.db, certs (after config)
#   /opt/Luminum/LuminumClient/logs/                client-stdout.log
#   /opt/Luminum/LuminumClient/run/                 client.pid
#   /opt/Luminum/LuminumClient/modules/<lumy>/      Lumy module binaries
#   /etc/systemd/system/luminum-client.service      service unit
#
# Maintainer scripts:
#   postinst  reloads systemd; imports /opt/Luminum/LuminumClient/config.ini if
#             present; enables + starts the service if the client is configured;
#             otherwise prints how to configure and start it.
#   prerm     stops the service before the files are removed.
#   postrm    reloads systemd after the unit file is removed.
#
# The .deb is a build artifact (gitignored); this script is the deliverable.
#
# Usage: bash mkdeb.sh [options]
#   --version V       package version (default: from Cargo.toml)
#   --binary P        client binary to package (default: build the release binary)
#   --no-build        do not build the release binary (requires --binary)
#   --out P           output .deb path (default: dist/luminum-client_<ver>_<arch>.deb)
#
set -u

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
CLIENT_DIR="$SCRIPT_DIR"
REPO=$(cd "$SCRIPT_DIR/../.." && pwd)

VERSION=""
BINARG=""
DO_BUILD=1
OUTARG=""

usage() {
	sed -n '2,32p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
	case "$1" in
		--version)  VERSION="${2:?--version requires a value}"; shift 2 ;;
		--binary)   BINARG="${2:?--binary requires a path}"; shift 2 ;;
		--no-build) DO_BUILD=0; shift ;;
		--out)      OUTARG="${2:?--out requires a path}"; shift 2 ;;
		-h|--help)  usage; exit 0 ;;
		*) echo "Unknown option: $1 (see --help)" >&2; exit 1 ;;
	esac
done

fail() { echo "ERROR: $*" >&2; exit 1; }

command -v dpkg-deb >/dev/null 2>&1 || fail "dpkg-deb is not available"

# --- version -----------------------------------------------------------------
if [ -z "$VERSION" ]; then
	VERSION=$(grep -m1 '^version' "$CLIENT_DIR/Cargo.toml" | sed 's/version *= *"\(.*\)"/\1/')
	[ -n "$VERSION" ] || fail "could not determine the version from Cargo.toml"
fi
ARCH=$(dpkg --print-architecture 2>/dev/null || echo amd64)

# --- client binary ------------------------------------------------------------
if [ -n "$BINARG" ]; then
	CLIENT_BIN="$BINARG"
elif [ "$DO_BUILD" -eq 1 ]; then
	echo "Building the release client binary..."
	( cd "$CLIENT_DIR" && cargo build --release --offline ) || fail "release build failed"
	CLIENT_BIN="$CLIENT_DIR/target/release/LuminumClient"
else
	fail "--no-build requires --binary"
fi
[ -x "$CLIENT_BIN" ] || fail "client binary not found or not executable: $CLIENT_BIN"

# --- staging tree --------------------------------------------------------------
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
PKG="$WORK/pkg"
ROOT=/opt/Luminum/LuminumClient

mkdir -p "$PKG/DEBIAN" \
	"$PKG$ROOT/bin" "$PKG$ROOT/config" "$PKG$ROOT/logs" "$PKG$ROOT/run" "$PKG$ROOT/modules" \
	"$PKG/etc/systemd/system" || fail "cannot create the staging tree"

# client binary
install -m 0755 "$CLIENT_BIN" "$PKG$ROOT/LuminumClient" || fail "cannot stage the client binary"

# runtime dirs (.keep is the Debian convention for "keep this otherwise-empty
# directory" so the install layout is explicit even before the client runs)
touch "$PKG$ROOT/config/.keep" "$PKG$ROOT/logs/.keep" "$PKG$ROOT/run/.keep" "$PKG$ROOT/modules/.keep"
chmod 0644 "$PKG$ROOT/config/.keep" "$PKG$ROOT/logs/.keep" "$PKG$ROOT/run/.keep" "$PKG$ROOT/modules/.keep"

# start/stop scripts (mirror install.sh; LUMINUM_HOME pinned to the install root)
cat > "$PKG$ROOT/bin/start-client" <<EOF
#!/bin/sh
# Luminum client start script (generated by install)
export LUMINUM_HOME="$ROOT"
cd "$ROOT"
nohup ./LuminumClient >> "$ROOT/logs/client-stdout.log" 2>&1 &
echo \$! > "$ROOT/run/client.pid"
echo "Luminum client started (PID \$(cat "$ROOT/run/client.pid"))"
EOF
cat > "$PKG$ROOT/bin/stop-client" <<EOF
#!/bin/sh
# Luminum client stop script (generated by install)
if [ -f "$ROOT/run/client.pid" ]; then
	PID=\$(cat "$ROOT/run/client.pid")
	kill "\$PID" 2>/dev/null && echo "Luminum client stopped (PID \$PID)"
	rm -f "$ROOT/run/client.pid"
else
	echo "Luminum client is not running (no pid file)"
fi
EOF
chmod 0700 "$PKG$ROOT/bin/start-client" "$PKG$ROOT/bin/stop-client" || fail "cannot write bin/ scripts"

# systemd unit (mirror install.sh)
cat > "$PKG/etc/systemd/system/luminum-client.service" <<EOF
# Luminum client service (generated by install)
[Unit]
Description=Luminum Client
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
Environment=LUMINUM_HOME="$ROOT"
WorkingDirectory=$ROOT
ExecStart=$ROOT/LuminumClient
Restart=on-failure

[Install]
WantedBy=multi-user.target
EOF
chmod 0644 "$PKG/etc/systemd/system/luminum-client.service" || fail "cannot write the service unit"

# --- Lumy modules (optional; include any prebuilt release binaries found) ------
MODSRC="$REPO/client/modules/linux"
MODCOUNT=0
if [ -d "$MODSRC" ]; then
	for mdir in "$MODSRC"/*/; do
		[ -d "$mdir" ] || continue
		mname=$(basename "$mdir")
		lumy=$(echo "$mname" | tr '[:upper:]' '[:lower:]')
		bin=$(ls "$mdir/target/release/"Lumy_* 2>/dev/null | head -n1)
		if [ -n "$bin" ] && [ -x "$bin" ]; then
			mkdir -p "$PKG$ROOT/modules/$lumy"
			install -m 0755 "$bin" "$PKG$ROOT/modules/$lumy/" || fail "cannot stage $bin"
			MODCOUNT=$((MODCOUNT + 1))
		fi
	done
fi
[ "$MODCOUNT" -gt 0 ] || echo "Note: no prebuilt Lumy modules found; the package ships the core client only."

# --- control file --------------------------------------------------------------
cat > "$PKG/DEBIAN/control" <<EOF
Package: luminum-client
Version: $VERSION
Section: admin
Priority: optional
Architecture: $ARCH
Maintainer: Christopher R. Curzio <ccurzio@luminum.net>
Depends: \${shlibs:Depends}
Description: Luminum endpoint client (Linux)
 Luminum is an open-source endpoint security and management platform.
 This package installs the Luminum client, which registers with the
 Luminum server, maintains a persistent MQTT control channel, and
 reports endpoint status to the server's web console.
EOF

# Compute the shared-library dependencies from the binary; fall back to a
# known-good list if dpkg-shlibdeps cannot resolve them.
if ! dpkg-shlibdeps -d"$PKG/DEBIAN" "$PKG$ROOT/LuminumClient" >/dev/null 2>&1; then
	echo "dpkg-shlibdeps could not resolve the dependencies; using a fixed list"
	sed -i 's/^Depends: .*/Depends: libc6, libssl3, libgcc-s1, libsqlite3-0, zlib1g, libzstd1/' "$PKG/DEBIAN/control"
fi

# --- maintainer scripts --------------------------------------------------------
cat > "$PKG/DEBIAN/postinst" <<'EOF'
#!/bin/sh
set -e
ROOT=/opt/Luminum/LuminumClient
if [ -x /usr/bin/systemctl ] && [ -f /etc/systemd/system/luminum-client.service ]; then
	/usr/bin/systemctl daemon-reload 2>/dev/null || true
fi
# If the operator placed a config.ini at the install root, import it so the
# client is pre-configured for its server (out-of-band provisioning).
if [ -f "$ROOT/config.ini" ] && [ ! -f "$ROOT/config/client.conf.db" ]; then
	echo "Importing provisioning file: $ROOT/config.ini"
	LUMINUM_HOME="$ROOT" "$ROOT/LuminumClient" --import "$ROOT/config.ini" || true
fi
# If the client is configured, enable and start the service; otherwise leave
# it stopped and tell the operator how to configure it.
if [ -f "$ROOT/config/client.conf.db" ]; then
	if [ -x /usr/bin/systemctl ]; then
		/usr/bin/systemctl enable luminum-client 2>/dev/null || true
		/usr/bin/systemctl start luminum-client 2>/dev/null || true
	elif [ -x "$ROOT/bin/start-client" ]; then
		"$ROOT/bin/start-client" || true
	fi
fi
echo
echo "Luminum Client installed to $ROOT"
if [ -f "$ROOT/config/client.conf.db" ]; then
	echo "  The client is configured; the service has been enabled and started."
else
	echo "  The client is not configured yet. To point it at a server, run:"
	echo "    $ROOT/LuminumClient --import /path/to/config.ini"
	echo "  (or the interactive wizard: $ROOT/LuminumClient -s)"
	echo "  then start it: $ROOT/bin/start-client"
fi
EOF
cat > "$PKG/DEBIAN/prerm" <<'EOF'
#!/bin/sh
set -e
if [ -x /usr/bin/systemctl ] && /usr/bin/systemctl is-active --quiet luminum-client 2>/dev/null; then
	/usr/bin/systemctl stop luminum-client 2>/dev/null || true
fi
if [ -x /opt/Luminum/LuminumClient/bin/stop-client ]; then
	/opt/Luminum/LuminumClient/bin/stop-client 2>/dev/null || true
fi
exit 0
EOF
cat > "$PKG/DEBIAN/postrm" <<'EOF'
#!/bin/sh
set -e
if [ -x /usr/bin/systemctl ]; then
	/usr/bin/systemctl daemon-reload 2>/dev/null || true
fi
exit 0
EOF
chmod 0755 "$PKG/DEBIAN/postinst" "$PKG/DEBIAN/prerm" "$PKG/DEBIAN/postrm" || fail "cannot set maintainer script permissions"

# --- build ---------------------------------------------------------------------
if [ -n "$OUTARG" ]; then
	OUT="$OUTARG"
else
	OUT="$CLIENT_DIR/dist/luminum-client_${VERSION}_${ARCH}.deb"
fi
mkdir -p "$(dirname "$OUT")" || fail "cannot create the output directory"
dpkg-deb --build --root-owner-group "$PKG" "$OUT" >/dev/null || fail "dpkg-deb build failed"

echo
echo "Built: $OUT"
echo
dpkg-deb --info "$OUT"
echo
dpkg-deb --contents "$OUT"
