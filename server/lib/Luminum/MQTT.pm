#
# Luminum::MQTT
#
# Server-side MQTT integration for the Luminum broker (protocol 4, 9).
#
# Provides:
#   - pure helpers for ACL generation, mosquitto password_file maintenance,
#     broker reload (SIGHUP), and command signing (unit-testable without a
#     broker or database);
#   - a forked MQTT worker that subscribes to the per-UID resp/status/events
#     topics, updates CLIENTS.STATUS from check-ins, and publishes commands
#     from the CLIENTS.COMMANDS outbox to their target topics;
#   - register/deactivate hooks that maintain the mosquitto password_file and
#     reload the broker so new/removed clients take effect.
#
# The worker runs in a forked child, isolated from the broker's blocking
# bootstrap listener loop. Net::MQTT::Simple handles broker reconnects
# (and re-sends subscriptions on each reconnect); the database handle is
# re-established lazily on failure.
#
package Luminum::MQTT;

use strict;
use warnings;

use DBI;
use JSON::PP;
use MIME::Base64;
use IO::Socket::SSL qw(SSL_VERIFY_PEER);
use Net::MQTT::Simple::SSL;
use Luminum::Protocol;

# --- Pure helpers -------------------------------------------------------------

# Build the mosquitto ACL file contents (protocol 4.3).
#
#   gen_acl(sid => $sid, server_user => $user, os_list => \@os, groups => \@groups)
#
# Per-endpoint topics use the %u substitution: each client may read its own
# cmd topic and write its own resp/status/events. Group topics cannot use +/#
# wildcards in a 'pattern' ACL, so the known OS values and group names are
# enumerated as explicit 'pattern read' lines. The server user is granted
# readwrite over the whole Luminum tree.
#
# OS values are restricted to [A-Za-z] (lowercased, since the OS topic is
# luminum/{SID}/os/{os}/cmd with a lowercase {os}) and group names to
# [A-Za-z0-9_.-] (exact case, since the client subscribes to the name as-is);
# anything else is dropped so a malformed name cannot inject ACL directives.
# Both lists are deduplicated.
sub gen_acl {
	my (%a) = @_;
	my $sid = $a{sid};
	my $server_user = $a{server_user};
	my (%seenos, @os);
	for my $o (@{ $a{os_list} // [] }) {
		next unless defined $o && $o =~ /^[A-Za-z]+$/;
		my $lo = lc($o);
		next if $seenos{$lo}++;
		push @os, $lo;
	}
	@os = sort @os;
	my (%seeng, @groups);
	for my $g (@{ $a{groups} // [] }) {
		next unless defined $g && $g =~ /^[A-Za-z0-9_.\-]+$/;
		next if $seeng{$g}++;
		push @groups, $g;
	}
	@groups = sort @groups;
	my $base = "luminum/$sid";

	my $acl = "# Luminum MQTT ACL (auto-generated by Luminum::MQTT; do not edit)\n";
	$acl .= "# Per-endpoint: each client reads its own cmd, writes its own resp/status/events.\n";
	$acl .= "pattern read  $base/%u/cmd\n";
	$acl .= "pattern write $base/%u/resp\n";
	$acl .= "pattern write $base/%u/status\n";
	$acl .= "pattern write $base/%u/events\n";
	$acl .= "# Group topics: readable by any authenticated client (isolation is by\n";
	$acl .= "# self-subscription). 'pattern' cannot use +/# wildcards, so the known\n";
	$acl .= "# OS values and group names are enumerated.\n";
	$acl .= "pattern read  $base/all/cmd\n";
	for my $os (@os) { $acl .= "pattern read  $base/os/$os/cmd\n"; }
	for my $g (@groups) { $acl .= "pattern read  $base/grp/$g/cmd\n"; }
	$acl .= "# Server: unrestricted within the Luminum tree (publishes commands, reads\n";
	$acl .= "# back resp/status/events).\n";
	$acl .= "user $server_user\n";
	$acl .= "topic readwrite $base/#\n";
	return $acl;
}

# Atomically write an ACL file (tmp + rename) with 0600 permissions.
sub write_acl {
	my ($path, $content) = @_;
	my $tmp = "$path.tmp.$$";
	open(my $fh, ">", $tmp) or die "Luminum::MQTT write_acl: cannot open $tmp: $!";
	print $fh $content or die "Luminum::MQTT write_acl: cannot write $tmp: $!";
	close($fh) or die "Luminum::MQTT write_acl: cannot close $tmp: $!";
	chmod(0600, $tmp);
	rename($tmp, $path) or die "Luminum::MQTT write_acl: cannot rename $tmp to $path: $!";
	return 1;
}

# Add (or update) a user in the mosquitto password_file. $uid is the
# mosquitto username: a client's numeric UID, or the server user (e.g.
# "luminum-server"). Only an empty name, or one that would break the
# password_file format (colon/newline), is rejected. Returns 1 on success,
# 0 on failure.
sub passwd_add {
	my ($file, $uid, $secret) = @_;
	return 0 unless defined $uid && length($uid) && $uid !~ /[:\n\r]/ && defined $secret && length($secret);
	my $rc = system("mosquitto_passwd", "-b", $file, $uid, $secret);
	return ($rc == 0) ? 1 : 0;
}

# Remove a user from the mosquitto password_file. $uid must be numeric.
# Returns 1 on success (including "user not present"), 0 on failure.
sub passwd_remove {
	my ($file, $uid) = @_;
	return 0 unless defined $uid && $uid =~ /^[0-9]+$/;
	my $rc = system("mosquitto_passwd", "-D", $file, $uid);
	return ($rc == 0) ? 1 : 0;
}

# Send SIGHUP to the mosquitto instance named by $pidfile so it re-reads its
# password_file and acl_file. Returns 1 on success, 0 on failure.
sub reload {
	my ($pidfile) = @_;
	return 0 unless defined $pidfile && -e $pidfile;
	open(my $pf, "<", $pidfile) or return 0;
	my $pid = <$pf>;
	close($pf);
	chomp($pid) if defined $pid;
	return 0 unless defined $pid && $pid =~ /^[0-9]+$/;
	return (kill("HUP", $pid) == 1) ? 1 : 0;
}

# Build, sign, and canonically encode a server command envelope (protocol 5).
# $data is an optional hashref placed in the envelope's data field. $id is an
# optional pre-chosen message id (the outbox QID); reusing it on a retry lets
# the client deduplicate a redelivered command. Returns the JSON bytes to
# publish.
sub sign_command {
	my ($seed, $uid, $lumy, $action, $data, $id) = @_;
	my $env = Luminum::Protocol::new_envelope(
		src => "server", uid => $uid, lumy => $lumy, action => $action, status => "OK"
	);
	$env->{id} = $id if defined $id && $id =~ /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
	$env->{data} = $data if defined $data;
	Luminum::Protocol::sign_envelope($env, $seed);
	return JSON::PP->new->utf8->canonical->encode($env);
}

# Map a COMMANDS.TARGET value to its MQTT topic (protocol 4.2). Returns undef
# if the target is not a recognized form.
sub target_topic {
	my ($sid, $target) = @_;
	my $base = "luminum/$sid";
	if (defined $target && $target =~ /^[0-9]+$/) { return "$base/$target/cmd"; }
	if (defined $target && $target eq "all") { return "$base/all/cmd"; }
	# The client subscribes to the lowercased OS topic (OSPLAT.to_lowercase()),
	# so the OS component is lowercased here to match.
	if (defined $target && $target =~ /^os\/([A-Za-z]+)$/) { return "$base/os/" . lc($1) . "/cmd"; }
	if (defined $target && $target =~ /^grp\/[A-Za-z0-9_.\-]+$/) { return "$base/$target/cmd"; }
	return undef;
}

# --- Broker / database integration --------------------------------------------

# Ensure a client's MQTT secret is in the password_file, then reload the
# broker. Called from the broker's registration path (protocol 7.1).
sub on_register {
	my ($uid, $secret, %cfg) = @_;
	my $ok = passwd_add($cfg{passwd_file}, $uid, $secret);
	reload($cfg{pid_file});
	return $ok;
}

# Remove a client's MQTT secret from the password_file, then reload the
# broker. Called from the broker's deactivation path (protocol 3.1).
sub on_deactivate {
	my ($uid, %cfg) = @_;
	my $ok = passwd_remove($cfg{passwd_file}, $uid);
	reload($cfg{pid_file});
	return $ok;
}

# Regenerate the ACL file from the known OS values (CLIENTS.STATUS.OSPLATFORM)
# and group names (CLIENTS.GROUPS.NAME), write it, and reload the broker.
# $dbh is a connected DBI handle to the CLIENTS database. Returns the ACL text.
sub regen_acl {
	my ($dbh, %cfg) = @_;
	my $sth = $dbh->prepare("select distinct OSPLATFORM from STATUS where OSPLATFORM is not null and OSPLATFORM != ''");
	$sth->execute();
	my @os = map { $_->[0] } @{ $sth->fetchall_arrayref() };
	$sth = $dbh->prepare("select NAME from GROUPS");
	$sth->execute();
	my @groups = map { $_->[0] } @{ $sth->fetchall_arrayref() };
	my $acl = gen_acl(sid => $cfg{sid}, server_user => $cfg{server_user}, os_list => \@os, groups => \@groups);
	write_acl($cfg{acl_file}, $acl);
	reload($cfg{pid_file});
	return $acl;
}

# --- The forked MQTT worker ---------------------------------------------------

# Open a DBI connection to the CLIENTS database. Returns a handle or undef.
sub _dbconnect {
	my (%a) = @_;
	my %attr = (PrintError => 0, RaiseError => 0, AutoCommit => 1);
	$attr{mysql_socket} = $a{dbsock} if $a{dbsock};
	$attr{mysql_host} = $a{dbhost} if $a{dbhost};
	return DBI->connect("DBI:mysql:" . ($a{dbname} // "CLIENTS"), $a{dbuser}, $a{dbpass}, \%attr);
}

# Lazily-maintained DB handle: returns a live handle, reconnecting if the
# connection dropped. Dies if it cannot connect.
sub _dbh {
	my ($db) = @_;
	return $db->{h} if $db->{h} && eval { $db->{h}->ping() };
	$db->{h} = _dbconnect(%{$db->{params}})
		or die "Luminum::MQTT worker: cannot connect to database: " . DBI->errstr;
	return $db->{h};
}

# Handle a check-in (status) message: update CLIENTS.STATUS. An offline LWT
# (status "offline") only flips CSTATE; a live check-in refreshes the fields.
sub _on_status {
	my ($db, $sid, $topic, $payload, $log) = @_;
	my ($uid) = $topic =~ m{^luminum/$sid/(\d+)/status$} or do { $log->("status: unparseable topic $topic"); return; };
	my $env = eval { JSON::PP->new->utf8->decode($payload) };
	return unless ref($env) eq "HASH";
	my $dbh = _dbh($db);
	if (($env->{status} // "") eq "offline") {
		$dbh->do("update STATUS set CSTATE = 'OFFLINE', LASTSEEN = now() where ID = ?", undef, $uid)
			or do { $log->("status: offline update failed for UID $uid: " . $dbh->errstr); return; };
		$log->("status: UID $uid offline");
	}
	else {
		my $data = (ref($env->{data}) eq "HASH") ? $env->{data} : {};
		my $sth = $dbh->prepare("update STATUS set HOSTNAME = ?, IPV4 = ?, OSPLATFORM = ?, OSRELEASE = ?, CLIENTVER = ?, CSTATE = 'OK', LASTSEEN = now() where ID = ?");
		$sth->execute($data->{hostname} // "", $data->{ipv4} // "", $data->{osplat} // "", $data->{osrel} // "", $data->{clientver} // "", $uid)
			or do { $log->("status: update failed for UID $uid: " . $dbh->errstr); return; };
		$log->("status: UID $uid OK");
	}
}

# Handle a response (resp) message: mark the matching outbox command ACKED.
# Correlation is by (uid, lumy, action) because the client echoes lumy/action
# and signs with its own UID but does not carry the command's message id.
sub _on_resp {
	my ($db, $sid, $topic, $payload, $log) = @_;
	my ($uid) = $topic =~ m{^luminum/$sid/(\d+)/resp$} or do { $log->("resp: unparseable topic $topic"); return; };
	my $env = eval { JSON::PP->new->utf8->decode($payload) };
	return unless ref($env) eq "HASH";
	my $lumy = $env->{lumy} // "";
	my $action = $env->{action} // "";
	my $dbh = _dbh($db);
	my $sth = $dbh->prepare("select ID from COMMANDS where STATUS = 'SENT' and LUMY = ? and ACTION = ? and (TARGET = ? or TARGET = 'all' or TARGET like 'os/%' or TARGET like 'grp/%') order by ID asc limit 1");
	$sth->execute($lumy, $action, $uid);
	my $id = $sth->fetchrow_array();
	if (defined $id) {
		$dbh->do("update COMMANDS set STATUS = 'ACKED', ACKED = now() where ID = ?", undef, $id);
		$log->("resp: UID $uid acked command $id ($lumy/$action)");
	}
	else {
		$log->("resp: UID $uid response ($lumy/$action) with no matching outbox command");
	}
}

# Handle an event message (logged only for now).
sub _on_events {
	my ($db, $sid, $topic, $payload, $log) = @_;
	my ($uid) = $topic =~ m{^luminum/$sid/(\d+)/events$} or return;
	my $env = eval { JSON::PP->new->utf8->decode($payload) };
	return unless ref($env) eq "HASH";
	$log->("events: UID $uid " . ($env->{action} // "?") . " " . ($env->{status} // ""));
}

# Publish PENDING outbox commands, and retry SENT commands past their deadline.
# A redelivered command reuses its stored QID as the envelope id so the client
# deduplicates it (protocol 9).
sub _pump_outbox {
	my ($db, $m, $sid, $seed, $log) = @_;
	my $dbh = _dbh($db);
	my $sth = $dbh->prepare("select ID, TARGET, LUMY, ACTION, DATA, QID from COMMANDS where STATUS = 'PENDING' or (STATUS = 'SENT' and DEADLINE is not null and DEADLINE < now()) order by ID asc limit 50");
	$sth->execute();
	while (my @row = $sth->fetchrow_array()) {
		my ($id, $target, $lumy, $action, $data, $qid) = @row;
		my $topic = target_topic($sid, $target);
		if (!defined $topic) {
			$dbh->do("update COMMANDS set STATUS = 'EXPIRED' where ID = ?", undef, $id);
			$log->("outbox: command $id has an invalid target '$target'; expired");
			next;
		}
		my $uid = ($target =~ /^[0-9]+$/) ? $target : "0";
		my $datahash = (defined $data && length($data)) ? eval { JSON::PP->new->utf8->decode($data) } : undef;
		my $payload = sign_command($seed, $uid, $lumy, $action, $datahash, $qid);
		$m->publish($topic, $payload);
		$dbh->do("update COMMANDS set STATUS = 'SENT', SENT = now(), DEADLINE = date_add(now(), interval 120 second) where ID = ?", undef, $id);
		$log->("outbox: published command $id ($lumy/$action) to $topic");
	}
}

# The main worker loop. Runs forever in a forked child.
#
# Config keys:
#   sid, host, port, ca, user, secret, seed   - MQTT connection + signing
#   dbname, dbuser, dbpass, dbsock, dbhost    - database connection
#   poll_secs                                 - outbox poll interval (default 1)
#   log                                       - coderef($msg) for logging
sub worker {
	my (%a) = @_;
	my $log = $a{log} || sub { };
	my $db = {
		params => { dbname => $a{dbname}, dbuser => $a{dbuser}, dbpass => $a{dbpass}, dbsock => $a{dbsock}, dbhost => $a{dbhost} },
		h => undef,
	};

	my $m = Net::MQTT::Simple::SSL->new("$a{host}:$a{port}", { SSL_ca_file => $a{ca}, SSL_verify_mode => SSL_VERIFY_PEER });
	$m->login($a{user}, $a{secret});

	my $base = "luminum/$a{sid}";
	$m->subscribe("$base/+/resp",   sub { _on_resp($db, $a{sid}, $_[0], $_[1], $log); });
	$m->subscribe("$base/+/status", sub { _on_status($db, $a{sid}, $_[0], $_[1], $log); });
	$m->subscribe("$base/+/events", sub { _on_events($db, $a{sid}, $_[0], $_[1], $log); });

	my $last = 0;
	while (1) {
		eval {
			$m->tick(0.25);
			if (time() - $last >= ($a{poll_secs} // 1)) {
				$last = time();
				_pump_outbox($db, $m, $a{sid}, $a{seed}, $log);
			}
			1;
		} or do { $log->("worker: " . $@); sleep 2; };
	}
}

1;
