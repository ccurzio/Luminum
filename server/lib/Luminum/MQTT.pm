#
# Luminum::MQTT
#
# Server-side MQTT integration for the Luminum broker (protocol 4, 9).
#
# Provides:
#   - pure helpers for ACL generation, mosquitto password_file maintenance,
#     broker reload (SIGHUP), and command signing (unit-testable without a
#     broker or database);
#   - a forked MQTT worker that subscribes to the per-UID resp/status/events
#     topics, updates CLIENTS.STATUS from check-ins, and publishes commands
#     from the CLIENTS.COMMANDS outbox to their target topics;
#   - register/deactivate hooks that maintain the mosquitto password_file and
#     reload the broker so new/removed clients take effect.
#
# The worker runs in a forked child, isolated from the broker's blocking
# bootstrap listener loop. Net::MQTT::Simple handles broker reconnects
# (and re-sends subscriptions on each reconnect); the database handle is
# re-established lazily on failure.
#
package Luminum::MQTT;

use strict;
use warnings;

use DBI;
use JSON::PP;
use MIME::Base64;
use POSIX qw(WNOHANG);
use IO::Socket::SSL qw(SSL_VERIFY_PEER);
use Net::MQTT::Simple::SSL;
use Luminum::Protocol;
use Luminum::P2P;
use Luminum::Repo;

# --- Pure helpers -------------------------------------------------------------

# Build the mosquitto ACL file contents (protocol 4.3).
#
#   gen_acl(sid => $sid, server_user => $user, os_list => \@os, groups => \@groups)
#
# Per-endpoint topics use the %u substitution: each client may read its own
# cmd topic and write its own resp/status/events. Group topics cannot use +/#
# wildcards in a 'pattern' ACL, so the known OS values and group names are
# enumerated as explicit 'pattern read' lines. The server user is granted
# readwrite over the whole Luminum tree.
#
# OS values are restricted to [A-Za-z] (lowercased, since the OS topic is
# luminum/{SID}/os/{os}/cmd with a lowercase {os}) and group names to
# [A-Za-z0-9_.-] (exact case, since the client subscribes to the name as-is);
# anything else is dropped so a malformed name cannot inject ACL directives.
# Both lists are deduplicated.
sub gen_acl {
	my (%a) = @_;
	my $sid = $a{sid};
	my $server_user = $a{server_user};
	my (%seenos, @os);
	for my $o (@{ $a{os_list} // [] }) {
		next unless defined $o && $o =~ /^[A-Za-z]+$/;
		my $lo = lc($o);
		next if $seenos{$lo}++;
		push @os, $lo;
	}
	@os = sort @os;
	my (%seeng, @groups);
	for my $g (@{ $a{groups} // [] }) {
		next unless defined $g && $g =~ /^[A-Za-z0-9_.\-]+$/;
		next if $seeng{$g}++;
		push @groups, $g;
	}
	@groups = sort @groups;
	my $base = "luminum/$sid";

	my $acl = "# Luminum MQTT ACL (auto-generated by Luminum::MQTT; do not edit)\n";
	$acl .= "# Per-endpoint: each client reads its own cmd, writes its own resp/status/events.\n";
	$acl .= "pattern read  $base/%u/cmd\n";
	$acl .= "pattern write $base/%u/resp\n";
	$acl .= "pattern write $base/%u/status\n";
	$acl .= "pattern write $base/%u/events\n";
	$acl .= "# Group topics: readable by any authenticated client (isolation is by\n";
	$acl .= "# self-subscription). 'pattern' cannot use +/# wildcards, so the known\n";
	$acl .= "# OS values and group names are enumerated.\n";
	$acl .= "pattern read  $base/all/cmd\n";
	for my $os (@os) { $acl .= "pattern read  $base/os/$os/cmd\n"; }
	for my $g (@groups) { $acl .= "pattern read  $base/grp/$g/cmd\n"; }
	$acl .= "# Server: unrestricted within the Luminum tree (publishes commands, reads\n";
	$acl .= "# back resp/status/events).\n";
	$acl .= "user $server_user\n";
	$acl .= "topic readwrite $base/#\n";
	return $acl;
}

# Capture a file's (uid, gid) so a root-side rewrite can restore it. On
# hosts where mosquitto runs as an unprivileged user, setup hands it the
# password/ACL files; if the broker's rewrites left them root-owned, the
# next mosquitto reload could not read them.
sub _file_owner {
	my ($path) = @_;
	my @st = stat($path);
	return @st ? ($st[4], $st[5]) : (undef, undef);
	}

sub _restore_owner {
	my ($path, $uid, $gid) = @_;
	return unless $> == 0 && defined $uid;
	chown($uid, $gid, $path);
	}

# Atomically write an ACL file (tmp + rename) with 0600 permissions.
sub write_acl {
	my ($path, $content) = @_;
	my ($ouid, $ogid) = _file_owner($path);
	my $tmp = "$path.tmp.$$";
	open(my $fh, ">", $tmp) or die "Luminum::MQTT write_acl: cannot open $tmp: $!";
	print $fh $content or die "Luminum::MQTT write_acl: cannot write $tmp: $!";
	close($fh) or die "Luminum::MQTT write_acl: cannot close $tmp: $!";
	chmod(0600, $tmp);
	rename($tmp, $path) or die "Luminum::MQTT write_acl: cannot rename $tmp to $path: $!";
	_restore_owner($path, $ouid, $ogid);
	return 1;
}

# Add (or update) a user in the mosquitto password_file. $uid is the
# mosquitto username: a client's numeric UID, or the server user (e.g.
# "luminum-server"). Only an empty name, or one that would break the
# password_file format (colon/newline), is rejected. Returns 1 on success,
# 0 on failure.
sub passwd_add {
	my ($file, $uid, $secret) = @_;
	return 0 unless defined $uid && length($uid) && $uid !~ /[:\n\r]/ && defined $secret && length($secret);
	my ($ouid, $ogid) = _file_owner($file);
	my $rc = system("mosquitto_passwd", "-b", $file, $uid, $secret);
	return 0 unless $rc == 0;
	_restore_owner($file, $ouid, $ogid);
	return 1;
}

# Remove a user from the mosquitto password_file. $uid must be numeric.
# Returns 1 on success (including "user not present"), 0 on failure.
sub passwd_remove {
	my ($file, $uid) = @_;
	return 0 unless defined $uid && $uid =~ /^[0-9]+$/;
	my ($ouid, $ogid) = _file_owner($file);
	my $rc = system("mosquitto_passwd", "-D", $file, $uid);
	return 0 unless $rc == 0;
	_restore_owner($file, $ouid, $ogid);
	return 1;
}

# Send SIGHUP to the mosquitto instance named by $pidfile so it re-reads its
# password_file and acl_file. Returns 1 on success, 0 on failure.
sub reload {
	my ($pidfile) = @_;
	return 0 unless defined $pidfile && -e $pidfile;
	open(my $pf, "<", $pidfile) or return 0;
	my $pid = <$pf>;
	close($pf);
	chomp($pid) if defined $pid;
	return 0 unless defined $pid && $pid =~ /^[0-9]+$/;
	return (kill("HUP", $pid) == 1) ? 1 : 0;
}

# Build, sign, and canonically encode a server command envelope (protocol 5).
# $data is an optional hashref placed in the envelope's data field. $id is an
# optional pre-chosen message id (the outbox QID); reusing it on a retry lets
# the client deduplicate a redelivered command. Returns the JSON bytes to
# publish.
sub sign_command {
	my ($seed, $uid, $lumy, $action, $data, $id) = @_;
	my $env = Luminum::Protocol::new_envelope(
		src => "server", uid => $uid, lumy => $lumy, action => $action, status => "OK"
	);
	$env->{id} = $id if defined $id && $id =~ /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
	$env->{data} = $data if defined $data;
	Luminum::Protocol::sign_envelope($env, $seed);
	return JSON::PP->new->utf8->canonical->encode($env);
}

# Map a COMMANDS.TARGET value to its MQTT topic (protocol 4.2). Returns undef
# if the target is not a recognized form.
sub target_topic {
	my ($sid, $target) = @_;
	my $base = "luminum/$sid";
	if (defined $target && $target =~ /^[0-9]+$/) { return "$base/$target/cmd"; }
	if (defined $target && $target eq "all") { return "$base/all/cmd"; }
	# The client subscribes to the lowercased OS topic (OSPLAT.to_lowercase()),
	# so the OS component is lowercased here to match.
	if (defined $target && $target =~ /^os\/([A-Za-z]+)$/) { return "$base/os/" . lc($1) . "/cmd"; }
	if (defined $target && $target =~ /^grp\/[A-Za-z0-9_.\-]+$/) { return "$base/$target/cmd"; }
	return undef;
}

# --- Broker / database integration --------------------------------------------

# Ensure a client's MQTT secret is in the password_file, then reload the
# broker. Called from the broker's registration path (protocol 7.1).
sub on_register {
	my ($uid, $secret, %cfg) = @_;
	my $ok = passwd_add($cfg{passwd_file}, $uid, $secret);
	reload($cfg{pid_file});
	return $ok;
}

# Remove a client's MQTT secret from the password_file, then reload the
# broker. Called from the broker's deactivation path (protocol 3.1).
sub on_deactivate {
	my ($uid, %cfg) = @_;
	my $ok = passwd_remove($cfg{passwd_file}, $uid);
	reload($cfg{pid_file});
	return $ok;
}

# Regenerate the ACL file from the known OS values (CLIENTS.STATUS.OSPLATFORM)
# and group names (CLIENTS.GROUPS.NAME), write it, and reload the broker.
# $dbh is a connected DBI handle to the CLIENTS database. Returns the ACL text.
sub regen_acl {
	my ($dbh, %cfg) = @_;
	my $sth = $dbh->prepare("select distinct OSPLATFORM from STATUS where OSPLATFORM is not null and OSPLATFORM != ''");
	$sth->execute();
	my @os = map { $_->[0] } @{ $sth->fetchall_arrayref() };
	$sth = $dbh->prepare("select NAME from GROUPS");
	$sth->execute();
	my @groups = map { $_->[0] } @{ $sth->fetchall_arrayref() };
	my $acl = gen_acl(sid => $cfg{sid}, server_user => $cfg{server_user}, os_list => \@os, groups => \@groups);
	write_acl($cfg{acl_file}, $acl);
	reload($cfg{pid_file});
	return $acl;
}

# --- The forked MQTT worker ---------------------------------------------------

# Open a DBI connection to the CLIENTS database. Returns a handle or undef.
sub _dbconnect {
	my (%a) = @_;
	my %attr = (PrintError => 0, RaiseError => 0, AutoCommit => 1);
	$attr{mysql_socket} = $a{dbsock} if $a{dbsock};
	$attr{mysql_host} = $a{dbhost} if $a{dbhost};
	return DBI->connect("DBI:mysql:" . ($a{dbname} // "CLIENTS"), $a{dbuser}, $a{dbpass}, \%attr);
}

# Lazily-maintained DB handle: returns a live handle, reconnecting if the
# connection dropped. Dies if it cannot connect.
sub _dbh {
	my ($db) = @_;
	return $db->{h} if $db->{h} && eval { $db->{h}->ping() };
	$db->{h} = _dbconnect(%{$db->{params}})
		or die "Luminum::MQTT worker: cannot connect to database: " . DBI->errstr;
	return $db->{h};
}

# Handle a check-in (status) message: update CLIENTS.STATUS. An offline LWT
# (status "offline") only flips CSTATE; a live check-in refreshes the fields
# and syncs the check-in interval (protocol 7.2).
sub _on_status {
	my ($db, $sysdb, $m, $seed, $sid, $topic, $payload, $log) = @_;
	my ($uid) = $topic =~ m{^luminum/$sid/(\d+)/status$} or do { $log->("status: unparseable topic $topic"); return; };
	my $env = eval { JSON::PP->new->utf8->decode($payload) };
	return unless ref($env) eq "HASH";
	my $dbh = _dbh($db);
	if (($env->{status} // "") eq "offline") {
		$dbh->do("update STATUS set CSTATE = 'OFFLINE', LASTSEEN = now() where ID = ?", undef, $uid)
			or do { $log->("status: offline update failed for UID $uid: " . $dbh->errstr); return; };
		$log->("status: UID $uid offline");
	}
	else {
		my $data = (ref($env->{data}) eq "HASH") ? $env->{data} : {};
		# A live check-in also clears the missing flag (protocol 7.5): a
		# client that was swept into the Missing Clients list and comes back
		# returns to the live list without any console action.
		my $sth = $dbh->prepare("update STATUS set HOSTNAME = ?, IPV4 = ?, OSPLATFORM = ?, OSRELEASE = ?, CLIENTVER = ?, CSTATE = 'OK', LASTSEEN = now(), MISSING = 0 where ID = ?");
		$sth->execute($data->{hostname} // "", $data->{ipv4} // "", $data->{osplat} // "", $data->{osrel} // "", $data->{clientver} // "", $uid)
			or do { $log->("status: update failed for UID $uid: " . $dbh->errstr); return; };
		$log->("status: UID $uid OK");
		_sync_checkin_interval($sysdb, $m, $seed, $sid, $uid, $data, $log);
	}
}

# Check-in interval sync (protocol 7.2): the client reports the interval it is
# currently using (data.checkin_secs, seconds). If it differs from the
# server's CHECKININT, the worker publishes a signed core/setcheckinint
# command on the client's cmd topic; the client persists and applies it.
# Because the comparison happens on every check-in, a freshly-installed client
# converges on its first check-in, an admin change to CHECKININT propagates on
# each client's next check-in (no broker restart - CHECKININT is read live),
# and a lost push self-heals on the following check-in.
sub _sync_checkin_interval {
	my ($sysdb, $m, $seed, $sid, $uid, $data, $log) = @_;
	my $reported = $data->{checkin_secs};
	return unless defined $reported && "$reported" =~ /^[0-9]+$/ && $reported > 0;
	my $want = _checkin_secs($sysdb, $log);
	return unless defined $want;
	return if $want == $reported;
	my $payload = sign_command($seed, $uid, "core", "setcheckinint", { checkin_secs => $want });
	$m->publish("luminum/$sid/$uid/cmd", $payload);
	$log->("status: UID $uid check-in interval differs (client ${reported}s, server ${want}s); pushed setcheckinint");
}

# The server-directed check-in interval in seconds (protocol 7.2): CHECKININT
# is stored in minutes in SYSTEM.CONFIG and is read live so an admin change
# takes effect on the next check-in without a broker restart. Returns undef
# when the value is absent or invalid.
sub _checkin_secs {
	my ($sysdb, $log) = @_;
	my $dbh = eval { _dbh($sysdb) };
	if ($@) { $log->("status: cannot read CHECKININT: $@"); return undef; }
	my @row = eval { $dbh->selectrow_array("select CVAL from CONFIG where CKEY = 'CHECKININT'") };
	return undef if $@;
	my $val = $row[0];
	return undef unless defined $val && $val =~ /^[0-9]+$/ && $val > 0;
	return $val * 60;
}

# Missing-client sweep (protocol 7.5): mark clients whose LASTSEEN is older
# than MISSINGAFTER days (SYSTEM.CONFIG, read live so an admin change takes
# effect on the next sweep) as MISSING, moving them from the Client Status
# list to the Missing Clients list. Deactivated clients (CSTATE = 'DEACT')
# are excluded - they left by choice, not by going dark. A live check-in
# clears the flag again, so a recovered client returns to the live list on
# its own. Runs once at worker startup and then hourly.
sub _sweep_missing {
	my ($db, $sysdb, $log) = @_;
	my $sysdbh = eval { _dbh($sysdb) };
	return if $@;
	my @row = eval { $sysdbh->selectrow_array("select CVAL from CONFIG where CKEY = 'MISSINGAFTER'") };
	return if $@;
	my $days = $row[0];
	return unless defined $days && $days =~ /^[0-9]+$/ && $days > 0;
	my $dbh = _dbh($db);
	my $n = $dbh->do("update STATUS set MISSING = 1 where MISSING = 0 and CSTATE != 'DEACT' and LASTSEEN is not null and LASTSEEN < date_sub(now(), interval $days day)")
		or do { $log->("missing: sweep update failed: " . $dbh->errstr); return; };
	# DBI reports affected-row counts in scientific notation ("0E0", "3E0"),
	# and the string "0E0" is true in a boolean context - normalize so the
	# count prints plainly and the guard below is numeric.
	$n = 0 + $n;
	if ($n > 0) {
		$log->("missing: marked $n client(s) missing (no check-in for $days day(s))");
	}
}

# Fold a P2P transfer report (docs/p2p.md 10) into the bookkeeping tables.
# Terminal reports (p2p_fetch_ok/fail) consume the token and upsert the
# holders; the folding is idempotent (a redelivered report for a consumed
# token changes nothing). Progress reports are logged until the
# P2PTRANSFERS folding lands (Phase 5). Returns 1 when the message was a
# P2P report (handled), 0 otherwise.
sub _on_p2p_report {
	my ($db, $contentdb, $uid, $data, $log) = @_;
	my $event = $data->{event} // "";
	if ($event eq "p2p_fetch_ok" || $event eq "p2p_fetch_fail") {
		# on_report takes live DBI handles; the worker passes the lazily
		# maintained connection specs.
		Luminum::P2P::on_report(_dbh($db), _dbh($contentdb), $uid, $data, $log);
		return 1;
	}
	if ($event eq "p2p_progress") {
		$log->("p2p: progress from UID $uid: fileid " . ($data->{fileid} // "?") . " " . ($data->{state} // "?") . " " . ($data->{received} // 0) . "/" . ($data->{total} // 0) . " bytes (source " . ($data->{srcuid} // "?") . ")");
		return 1;
	}
	return 0;
}

# Handle a response (resp) message. An answer to a query is correlated by
# data.qid (protocol 7.3: the client echoes the query's qid, which is the
# outbox QID, the command envelope id, and data.qid in one value); its
# per-sensor results are stored in QUERYRESULTS. Other responses (setgroups,
# config, ...) carry no qid, so correlation stays by (uid, lumy, action):
# the client echoes lumy/action but does not carry the command's message id.
# P2P transfer reports (docs/p2p.md 10) are client-originated core/report
# messages: p2p_fetch_ok/fail are folded into the token and holder tables
# (Phase 3); p2p_progress is logged until the P2PTRANSFERS folding lands
# (Phase 5).
sub _on_resp {
	my ($db, $contentdb, $sid, $topic, $payload, $log) = @_;
	my ($uid) = $topic =~ m{^luminum/$sid/(\d+)/resp$} or do { $log->("resp: unparseable topic $topic"); return; };
	my $env = eval { JSON::PP->new->utf8->decode($payload) };
	return unless ref($env) eq "HASH";
	my $lumy = $env->{lumy} // "";
	my $action = $env->{action} // "";
	my $data = (ref($env->{data}) eq "HASH") ? $env->{data} : undef;
	if ($action eq "report" && defined $data && _on_p2p_report($db, $contentdb, $uid, $data, $log)) {
		return;
	}
	if ($action eq "answer" && defined $data) {
		_on_answer($db, $uid, $data, $env->{status}, $log);
		return;
	}
	my $dbh = _dbh($db);
	my $sth = $dbh->prepare("select ID from COMMANDS where STATUS = 'SENT' and LUMY = ? and ACTION = ? and (TARGET = ? or TARGET = 'all' or TARGET like 'os/%' or TARGET like 'grp/%') order by ID asc limit 1");
	$sth->execute($lumy, $action, $uid);
	my $id = $sth->fetchrow_array();
	if (defined $id) {
		$dbh->do("update COMMANDS set STATUS = 'ACKED', ACKED = now() where ID = ?", undef, $id);
		$log->("resp: UID $uid acked command $id ($lumy/$action)");
	}
	else {
		$log->("resp: UID $uid response ($lumy/$action) with no matching outbox command");
	}
}

# Handle a query answer (protocol 6.1, 7.3): store each per-sensor results
# entry in QUERYRESULTS and mark the command ACKED on the first answer. A
# broadcast query is answered by every matching endpoint, so the duplicate
# check is per (QID, UID), not per QID: a redelivered answer from the same
# endpoint (QoS 1) is logged and dropped, while the other endpoints' answers
# are stored. An answer past the command's deadline is dropped - the answer
# window is closed whether the command was TIMEDOUT (no answer by the
# deadline) or ACKed by a first answer and the deadline has since passed.
#
# A NO_MATCH answer (7.3: the query's condition tree evaluated false on the
# endpoint) carries no results. It is recorded in QUERYNOMATCH - one row per
# (QID, UID), the unique key deduplicating a QoS 1 redelivery - so the
# console's query clock knows every endpoint in the target has either
# answered or reported no match. A no-match is not an answer: it stores no
# results and does not ACK the command, so a query no endpoint matches stays
# SENT and times out at its deadline exactly as before.
sub _on_answer {
	my ($db, $uid, $data, $status, $log) = @_;
	my $qid = $data->{qid};
	if (!defined $qid || $qid !~ /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/) {
		$log->("answer: UID $uid answer without a valid data.qid; not correlated");
		return;
	}
	my $dbh = _dbh($db);
	my $sth = $dbh->prepare("select ID, STATUS, (DEADLINE is not null and DEADLINE < now()) from COMMANDS where QID = ?");
	$sth->execute($qid);
	my ($id, $cstatus, $late) = $sth->fetchrow_array();
	if (!defined $id) {
		$log->("answer: UID $uid answer for unknown qid $qid (no matching outbox command)");
		return;
	}
	if ($cstatus eq "TIMEDOUT" || $late) {
		$log->("answer: late answer from UID $uid for command $id (answer window closed); ignored");
		return;
	}
	if (defined $status && $status eq "NO_MATCH") {
		# An endpoint that already answered this query cannot also report no
		# match (the condition evaluation is deterministic per endpoint); a
		# stray no-match after an answer is logged and dropped.
		my $answered = $dbh->prepare("select 1 from QUERYRESULTS where QID = ? and UID = ? limit 1");
		$answered->execute($qid, $uid);
		if ($answered->fetchrow_array()) {
			$log->("answer: UID $uid no-match for command $id after an answer; ignored");
			return;
		}
		my $nm = $dbh->prepare("select 1 from QUERYNOMATCH where QID = ? and UID = ? limit 1");
		$nm->execute($qid, $uid);
		if ($nm->fetchrow_array()) {
			$log->("answer: duplicate no-match from UID $uid for command $id; ignored");
			return;
		}
		$dbh->do("insert into QUERYNOMATCH (CMDID,QID,UID,TS) values (?,?,?,now())", undef, $id, $qid, $uid);
		$log->("answer: UID $uid reported no match for query $qid (command $id)");
		return;
	}
	my $dup = $dbh->prepare("select 1 from QUERYRESULTS where QID = ? and UID = ? limit 1");
	$dup->execute($qid, $uid);
	if ($dup->fetchrow_array()) {
		$log->("answer: duplicate answer from UID $uid for command $id; ignored");
		return;
	}
	# The first answer ACKs the command; the remaining endpoints of a
	# broadcast query keep answering (their UIDs are not in QUERYRESULTS yet).
	if ($cstatus ne "ACKED") {
		$dbh->do("update COMMANDS set STATUS = 'ACKED', ACKED = now() where ID = ?", undef, $id);
	}
	my $results = (ref($data->{results}) eq "ARRAY") ? $data->{results} : [];
	my $ins = $dbh->prepare("insert into QUERYRESULTS (CMDID,QID,UID,SENSORID,STATUS,OUTPUT,ERR,TS) values (?,?,?,?,?,?,?,now())");
	my $stored = 0;
	for my $r (@$results) {
		next unless ref($r) eq "HASH" && defined $r->{sid} && "$r->{sid}" =~ /^[0-9]+$/;
		my $ok = (defined $r->{output} && !ref($r->{output}));
		$ins->execute($id, $qid, $uid, $r->{sid}, $ok ? "OK" : "ERR",
			$ok ? $r->{output} : undef,
			($ok || !defined $r->{err} || ref($r->{err})) ? undef : $r->{err});
		$stored++;
	}
	$log->("answer: UID $uid answered query $qid (command $id, $stored result(s) stored)");
}

# Handle an event message. Terminal P2P transfer reports queued on the
# client's out-queue while the control channel was down (protocol 9.1) are
# flushed to the events topic on reconnect, so the report folding runs here
# as well as on the resp topic (it is idempotent). Everything else is
# logged.
sub _on_events {
	my ($db, $contentdb, $sid, $topic, $payload, $log) = @_;
	my ($uid) = $topic =~ m{^luminum/$sid/(\d+)/events$} or return;
	my $env = eval { JSON::PP->new->utf8->decode($payload) };
	return unless ref($env) eq "HASH";
	my $data = (ref($env->{data}) eq "HASH") ? $env->{data} : undef;
	if (($env->{action} // "") eq "report" && defined $data
		&& _on_p2p_report($db, $contentdb, $uid, $data, $log)) {
		return;
	}
	$log->("events: UID $uid " . ($env->{action} // "?") . " " . ($env->{status} // ""));
}

# The deadline for an action (protocol 9.3): query and other commands use
# CMDTIMEOUT, deploy uses DEPLTIMEOUT.
sub _action_timeout {
	my ($action, $cmd, $depl) = @_;
	return ($action eq "deploy") ? $depl : $cmd;
}

# Publish PENDING outbox commands, and handle SENT commands past their
# deadline (protocol 7.3, 9). A redelivered command reuses its stored QID as
# the envelope id so the client deduplicates it. Retry policy (v1): a query
# that gets no answer by its deadline is terminal - it is marked TIMEDOUT and
# not republished (a redelivered query would be deduplicated client-side and
# never re-answered); the console re-enqueues it if it wants a retry. Other
# actions are republished past their deadline.
#
# Deploy commands (docs/p2p.md 5, 7.1) are published in the grant form: each
# publish attempt mints a fresh single-use grant (a redelivered command must
# carry a grant that has not expired) and embeds it in the command's ref, and
# the seed path pushes the package files to the target's 10704 in a forked
# child (the session is blocking and can last as long as the download).
# $ssl is {cert, key, server_ip} or undef (tests without TLS material);
# $push_children is an arrayref the worker reaps.
sub _pump_outbox {
	my ($db, $contentdb, $m, $sid, $seed, $cmd_timeout, $depl_timeout, $ssl, $content_root, $push_children, $log) = @_;
	my $dbh = _dbh($db);
	my $sth = $dbh->prepare("select ID, TARGET, LUMY, ACTION, DATA, QID, STATUS from COMMANDS where STATUS = 'PENDING' or (STATUS = 'SENT' and DEADLINE is not null and DEADLINE < now()) order by ID asc limit 50");
	$sth->execute();
	while (my @row = $sth->fetchrow_array()) {
		my ($id, $target, $lumy, $action, $data, $qid, $status) = @row;
		if ($status eq "SENT" && $action eq "query") {
			$dbh->do("update COMMANDS set STATUS = 'TIMEDOUT' where ID = ?", undef, $id);
			$log->("outbox: query command $id got no answer by its deadline; marked TIMEDOUT");
			next;
		}
		my $topic = target_topic($sid, $target);
		if (!defined $topic) {
			$dbh->do("update COMMANDS set STATUS = 'EXPIRED' where ID = ?", undef, $id);
			$log->("outbox: command $id has an invalid target '$target'; expired");
			next;
		}
		my $uid = ($target =~ /^[0-9]+$/) ? $target : "0";
		my $datahash = (defined $data && length($data)) ? eval { JSON::PP->new->utf8->decode($data) } : undef;
		$datahash = {} unless ref($datahash) eq "HASH";

		if ($action eq "deploy") {
			# The grant is per target (it names the requester UID and the
			# target's OS), so a deploy must target a single endpoint.
			unless ($target =~ /^[0-9]+$/) {
				$dbh->do("update COMMANDS set STATUS = 'EXPIRED' where ID = ?", undef, $id);
				$log->("outbox: deploy command $id targets '$target'; deploys require a single endpoint (the grant is per target); expired");
				next;
			}
			my $pkgid = $datahash->{pkgid};
			unless (defined $pkgid && "$pkgid" =~ /^[0-9]+$/) {
				$dbh->do("update COMMANDS set STATUS = 'EXPIRED' where ID = ?", undef, $id);
				$log->("outbox: deploy command $id has no valid pkgid; expired");
				next;
			}
			my @osrow = $dbh->selectrow_array("select OSPLATFORM from STATUS where ID = ?", undef, $target);
			my $os = $osrow[0];
			unless (defined $os && length $os) {
				$dbh->do("update COMMANDS set STATUS = 'EXPIRED' where ID = ?", undef, $id);
				$log->("outbox: deploy command $id: no OS on record for UID $target; expired");
				next;
			}
			my ($mok, $grant, $token) = Luminum::P2P::mint_grant(
				contentdbh => _dbh($contentdb), dbh => $dbh, seed => $seed,
				uid => $target, pkgid => $pkgid, os => $os,
				aid => (defined $datahash->{aid} && length($datahash->{aid})) ? $datahash->{aid} : $qid,
				server_ip => $ssl ? $ssl->{server_ip} : undef, log => $log,
				);
			unless ($mok) {
				$dbh->do("update COMMANDS set STATUS = 'EXPIRED' where ID = ?", undef, $id);
				$log->("outbox: deploy command $id: $grant (grant minting failed); expired");
				next;
			}
			$datahash->{ref} = { channel => "p2p", grant => $grant };
			my $payload = sign_command($seed, $uid, $lumy, $action, $datahash, $qid);
			$m->publish($topic, $payload);
			my $timeout = _action_timeout($action, $cmd_timeout, $depl_timeout);
			$dbh->do("update COMMANDS set STATUS = 'SENT', SENT = now(), DEADLINE = date_add(now(), interval $timeout second) where ID = ?", undef, $id);
			$log->("outbox: published deploy command $id to $topic (grant $token, deadline ${timeout}s)");
			# Seed path (docs/p2p.md 3): push the files to the target's
			# inbound data channel. The client's 10704 listener is bound at
			# startup, so the push may race the command delivery - the grant
			# is self-authenticating, the session does not depend on the
			# command having been processed.
			my @iprow = $dbh->selectrow_array("select IPV4 from STATUS where ID = ?", undef, $target);
			my $ip = $iprow[0];
			if ($ssl && defined $ip && length $ip) {
				my @pubrow = $dbh->selectrow_array("select PUBKEY from AUTH where ID = ?", undef, $target);
				my $clpubraw = (defined $pubrow[0] && length $pubrow[0])
					? Luminum::Protocol::spki_to_raw(decode_base64($pubrow[0]))
					: undef;
				my $pid = fork();
				if (!defined $pid) {
					$log->("outbox: deploy command $id: unable to fork the push child: $!");
				}
				elsif ($pid == 0) {
					my ($pok, $perr) = Luminum::P2P::push_grant(
						grant => $grant, uid => $target, ip => $ip,
						seed => $seed,
						sslcert => $ssl->{cert}, sslprvkey => $ssl->{key},
						clpubraw => $clpubraw, content_root => $content_root, log => $log,
						);
					$log->("outbox: deploy command $id: push session failed: $perr") unless $pok;
					exit($pok ? 0 : 1);
				}
				else {
					push @$push_children, $pid;
					$log->("outbox: deploy command $id: push child $pid started (grant $token to $ip)");
				}
			}
			else {
				$log->("outbox: deploy command $id: no push attempted (no TLS material or no IP on record for UID $target)");
			}
			next;
		}

		my $payload = sign_command($seed, $uid, $lumy, $action, $datahash, $qid);
		$m->publish($topic, $payload);
		my $timeout = _action_timeout($action, $cmd_timeout, $depl_timeout);
		$dbh->do("update COMMANDS set STATUS = 'SENT', SENT = now(), DEADLINE = date_add(now(), interval $timeout second) where ID = ?", undef, $id);
		$log->("outbox: published command $id ($lumy/$action) to $topic (deadline ${timeout}s)");
	}
}

# Process console-queued endpoint deregistrations (protocol 6.1). The
# console's Deregister action inserts a PENDING DEREGS row; each row here
# removes the endpoint from the server - the client's secret from the
# mosquitto password_file (the web console cannot maintain that file) plus
# the CLIENTS.AUTH and CLIENTS.STATUS rows - and marks the row DONE. Unlike
# the broker's client-initiated path (which deactivates, leaving the record
# so the fingerprint cannot be silently re-registered), the console action
# deletes the record: with the AUTH row gone the bootstrap channel rejects
# the client (no stored public key to verify its signature against) and
# MQTT login fails (no password_file entry). The secret is removed before
# the rows are deleted, so on the success path the credentials are gone
# first. Both deletes and passwd_remove are idempotent, so a row whose
# client was already removed still completes.
sub _pump_deregs {
	my ($db, $log, $passwd_file, $pid_file) = @_;
	my $dbh = _dbh($db);
	my $sth = $dbh->prepare("select ID, UID from DEREGS where STATUS = 'PENDING' order by ID asc limit 50");
	$sth->execute();
	while (my @row = $sth->fetchrow_array()) {
		my ($id, $uid) = @row;
		if (passwd_remove($passwd_file, $uid)) {
			reload($pid_file);
		}
		else {
			$log->("dereg: UID $uid removal proceeded, but the MQTT password_file removal failed ($passwd_file)");
		}
		$dbh->do("delete from AUTH where ID = ?", undef, $uid);
		$dbh->do("delete from STATUS where ID = ?", undef, $uid);
		$dbh->do("update DEREGS set STATUS = 'DONE', DONE = now() where ID = ?", undef, $id);
		$log->("dereg: removed client ID $uid (console request $id)");
	}
}

# Ensure the worker's tables exist (protocol 7.3, 6.1). schema.sql creates
# them for installed databases; this covers a worker pointed at a database
# that predates them.
sub _ensure_schema {
	my ($db) = @_;
	my $dbh = _dbh($db);
	$dbh->do(qq{
		create table if not exists QUERYRESULTS (
			ID int(20) not null auto_increment,
			CMDID int(20) not null,
			QID char(36) not null,
			UID int(20) not null,
			SENSORID int(20) not null,
			STATUS tinytext not null,
			OUTPUT mediumtext default null,
			ERR tinytext default null,
			TS datetime not null,
			primary key (ID),
			key IDX_QUERYRESULTS_QID (QID)
		) engine=InnoDB default charset=utf8mb4
	});
	$dbh->do(qq{
		create table if not exists QUERYNOMATCH (
			ID int(20) not null auto_increment,
			CMDID int(20) not null,
			QID char(36) not null,
			UID int(20) not null,
			TS datetime not null,
			primary key (ID),
			unique key UQ_QUERYNOMATCH (QID, UID)
		) engine=InnoDB default charset=utf8mb4
	});
	$dbh->do(qq{
		create table if not exists DEREGS (
			ID int(20) not null auto_increment,
			UID int(20) not null,
			REQUESTED datetime not null,
			STATUS tinytext not null default 'PENDING',
			DONE datetime default null,
			primary key (ID),
			key IDX_DEREGS_STATUS (STATUS)
		) engine=InnoDB default charset=utf8mb4
	});
	# P2P transfer bookkeeping (docs/p2p.md 9): single-use grants and live
	# transfer progress.
	$dbh->do(qq{
		create table if not exists P2PTOKENS (
			TOKEN char(36) not null,
			PKGID int(20) not null,
			REQUID int(20) not null,
			SOURCES tinytext not null,
			EXPIRES datetime not null,
			USED datetime default null,
			primary key (TOKEN),
			key IDX_P2PTOKENS_EXPIRES (EXPIRES)
		) engine=InnoDB default charset=utf8mb4
	});
	$dbh->do(qq{
		create table if not exists P2PTRANSFERS (
			ID int(20) not null auto_increment,
			AID char(36) not null,
			UID int(20) not null,
			FILEID int(20) not null,
			STATE tinytext not null,
			RECEIVED bigint(20) not null default 0,
			TOTAL bigint(20) not null default 0,
			SRCUID int(20) default null,
			ERR tinytext default null,
			TS datetime not null,
			primary key (ID),
			unique key UQ_P2PTRANSFERS (AID,UID,FILEID)
		) engine=InnoDB default charset=utf8mb4
	});
}

# Ensure the CONTENT database's P2P table exists (docs/p2p.md 9). schema.sql
# creates it for installed databases; this covers a worker pointed at a
# database that predates it.
sub _ensure_content_schema {
	my ($contentdb) = @_;
	my $dbh = _dbh($contentdb);
	$dbh->do(qq{
		create table if not exists PKGHOLDERS (
			ID int(20) not null auto_increment,
			FILEID int(20) not null,
			UID int(20) not null,
			SOURCE tinytext not null,
			TS datetime not null,
			primary key (ID),
			unique key UQ_PKGHOLDERS (FILEID,UID)
		) engine=InnoDB default charset=utf8mb4
	});
}

# The main worker loop. Runs forever in a forked child.
#
# Config keys:
#   sid, host, port, ca, user, secret, seed   - MQTT connection + signing
#   dbname, dbuser, dbpass, dbsock, dbhost    - database connection
#   sysdb_name                                - SYSTEM database name (default
#                                               "SYSTEM"; the server config the
#                                               worker reads live)
#   poll_secs                                 - outbox poll interval (default 1)
#   cmd_timeout, depl_timeout                 - command deadlines in seconds
#                                               (protocol 9.3; defaults 120/3600)
#   passwd_file, pid_file                     - mosquitto password_file and
#                                               pid file (console-queued
#                                               deregistrations remove the
#                                               client's secret and reload
#                                               the broker)
#   sslcert, sslprvkey, server_ip             - the server TLS certificate,
#                                               its key, and the address
#                                               recorded in seed-path grants
#                                               (docs/p2p.md 3); absent in
#                                               tests, where no push is made
#   log                                       - coderef($msg) for logging
sub worker {
	my (%a) = @_;
	my $log = $a{log} || sub { };
	my $db = {
		params => { dbname => $a{dbname}, dbuser => $a{dbuser}, dbpass => $a{dbpass}, dbsock => $a{dbsock}, dbhost => $a{dbhost} },
		h => undef,
	};
	# The SYSTEM database holds CHECKININT (protocol 7.2) and MISSINGAFTER
	# (protocol 7.5); the worker reads them live so an admin change propagates
	# on the next check-in / sweep without a broker restart. Same
	# credentials/socket as the CLIENTS database.
	my $sysdb = {
		params => { dbname => ($a{sysdb_name} // "SYSTEM"), dbuser => $a{dbuser}, dbpass => $a{dbpass}, dbsock => $a{dbsock}, dbhost => $a{dbhost} },
		h => undef,
	};
	# The CONTENT database holds the file repository catalog (docs/p2p.md
	# Phase 0); the discovery scan registers files dropped into the
	# staging area. Same credentials/socket as the other databases.
	my $contentdb = {
		params => { dbname => "CONTENT", dbuser => $a{dbuser}, dbpass => $a{dbpass}, dbsock => $a{dbsock}, dbhost => $a{dbhost} },
		h => undef,
	};
	my $cmd_timeout = ($a{cmd_timeout} && $a{cmd_timeout} =~ /^[0-9]+$/) ? $a{cmd_timeout} : 120;
	my $depl_timeout = ($a{depl_timeout} && $a{depl_timeout} =~ /^[0-9]+$/) ? $a{depl_timeout} : 3600;
	# Seed-path push material (docs/p2p.md 3): the server TLS certificate and
	# key the push presents, plus the address recorded in the grant's server
	# source entry. Absent in tests, where deploys publish but never push.
	my $ssl = (defined $a{sslcert} && defined $a{sslprvkey})
		? { cert => $a{sslcert}, key => $a{sslprvkey}, server_ip => $a{server_ip} }
		: undef;

	my $m = Net::MQTT::Simple::SSL->new("$a{host}:$a{port}", { SSL_ca_file => $a{ca}, SSL_verify_mode => SSL_VERIFY_PEER });
	$m->login($a{user}, $a{secret});

	my $base = "luminum/$a{sid}";
	$m->subscribe("$base/+/resp",   sub { _on_resp($db, $contentdb, $a{sid}, $_[0], $_[1], $log); });
	$m->subscribe("$base/+/status", sub { _on_status($db, $sysdb, $m, $a{seed}, $a{sid}, $_[0], $_[1], $log); });
	$m->subscribe("$base/+/events", sub { _on_events($db, $contentdb, $a{sid}, $_[0], $_[1], $log); });

	my $schema_ok = 0;
	my $last = 0;
	# Forked seed-path push children (docs/p2p.md 3), reaped non-blocking so
	# a long transfer never blocks the tick loop and no zombie accumulates.
	my @push_children;
	# The missing-client sweep (protocol 7.5) runs hourly; the zero start
	# value makes the first sweep happen at startup, so clients that went
	# dark while the server was down are caught as soon as it comes back.
	my $last_sweep = 0;
	# The repository discovery scan (docs/p2p.md Phase 0) runs every 60 s;
	# the zero start value makes the first scan happen at startup, so files
	# dropped while the server was down are caught as soon as it comes
	# back. Skipped when no content root is configured (tests).
	my $last_repo_scan = 0;
	while (1) {
		eval {
			$m->tick(0.25);
			unless ($schema_ok) {
				_ensure_schema($db);
				eval { _ensure_content_schema($contentdb); } or do { $log->("worker: content schema: $@"); };
				$schema_ok = 1;
			}
			# Reap finished push children (WNOHANG: a transfer in flight is
			# not waited for).
			while (@push_children) {
				my $pid = waitpid($push_children[0], WNOHANG);
				last unless $pid > 0;
				shift @push_children;
				my $code = ($? >> 8);
				$log->("p2p: push child $pid exited (status $code)") if $code != 0;
			}
			if (time() - $last >= ($a{poll_secs} // 1)) {
				$last = time();
				_pump_outbox($db, $contentdb, $m, $a{sid}, $a{seed}, $cmd_timeout, $depl_timeout, $ssl, $a{content_root}, \@push_children, $log);
				# Console-queued deregistrations need the mosquitto
				# password_file to remove the client's secret; a worker
				# started without it (tests) skips the pump.
				_pump_deregs($db, $log, $a{passwd_file}, $a{pid_file}) if defined $a{passwd_file};
			}
			if (time() - $last_sweep >= 3600) {
				$last_sweep = time();
				_sweep_missing($db, $sysdb, $log);
			}
			if (defined $a{content_root} && time() - $last_repo_scan >= 60) {
				$last_repo_scan = time();
				eval {
					Luminum::Repo::scan(
						root => $a{content_root},
						contentdbh => _dbh($contentdb),
						sysdbh => _dbh($sysdb),
						log => $log,
						);
				} or do { $log->("repo: scan failed: $@"); };
			}
			1;
		} or do { $log->("worker: " . $@); sleep 2; };
	}
}

